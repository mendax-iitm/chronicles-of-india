// scripts/enrich-waterways.mjs
// Adds appear / vanish metadata and historical canals/waterways to data/base.json and data/base.js
// Based on BRIEF.md §6.2: Saraswati drying, Grand Anicut (c. 150 CE), Western Yamuna Canal (1356 CE), Ganges Canal (1854 CE).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

process.chdir(resolve(dirname(fileURLToPath(import.meta.url)), '..'));

const base = JSON.parse(readFileSync('data/base.json', 'utf8'));

// Enrich existing rivers with default appear/vanish if not present
base.rivers.forEach(r => {
  if (r.appear == null) r.appear = -10000;
  if (r.vanish == null) r.vanish = 10000;
});

// Remove previously added historic canals if re-running
base.rivers = base.rivers.filter(r => !['Saraswati (Ghaggar-Hakra)', 'Grand Anicut (Kallanai)', 'Western Yamuna Canal', 'Upper Ganges Canal', 'Upper Bari Doab Canal'].includes(r.name));

const historicWaterways = [
  {
    name: "Saraswati (Ghaggar-Hakra)",
    rank: 1,
    appear: -10000,
    vanish: -600, // dried up as a perennial snow-fed river by early historical period
    line: [
      [[77.10, 30.50], [76.50, 29.98], [75.80, 29.50], [75.00, 29.10], [73.80, 28.50], [72.50, 27.80], [71.00, 26.90], [69.50, 25.50], [68.80, 24.20]]
    ],
    label: [74.5, 29.0]
  },
  {
    name: "Grand Anicut (Kallanai)",
    rank: 0,
    appear: 150, // Built by Karikala Chola c. 150 CE
    vanish: 10000,
    line: [
      [[78.78, 10.83], [78.82, 10.84], [78.95, 10.82], [79.15, 10.85], [79.35, 10.90], [79.65, 10.85], [79.85, 10.80]]
    ],
    label: [79.0, 10.84]
  },
  {
    name: "Western Yamuna Canal",
    rank: 0,
    appear: 1356, // Dug by Firoz Shah Tughlaq in 1356
    vanish: 10000,
    line: [
      [[77.30, 30.25], [77.15, 29.95], [77.00, 29.40], [77.05, 28.90], [77.18, 28.68]]
    ],
    label: [77.05, 29.5]
  },
  {
    name: "Upper Ganges Canal",
    rank: 0,
    appear: 1854, // Opened by Lord Dalhousie in 1854
    vanish: 10000,
    line: [
      [[78.17, 29.95], [78.00, 29.50], [77.85, 29.00], [78.10, 28.30], [78.60, 27.50], [80.30, 26.45]]
    ],
    label: [78.0, 29.2]
  },
  {
    name: "Upper Bari Doab Canal",
    rank: 0,
    appear: 1859, // Constructed by British engineers 1859
    vanish: 10000,
    line: [
      [[75.60, 32.25], [75.30, 31.85], [74.90, 31.50], [74.40, 31.10]]
    ],
    label: [75.1, 31.6]
  }
];

base.rivers.push(...historicWaterways);
base.rivers.sort((a, b) => a.name.localeCompare(b.name));

writeFileSync('data/base.json', JSON.stringify(base, null, 2) + '\n');
writeFileSync('data/base.js', `// Base geography generated by scripts/build-geo.mjs and enriched with dynamic waterways\nwindow.ATLAS_BASE = ${JSON.stringify(base)};\n`);

console.log(`Enriched data/base.json and data/base.js with ${historicWaterways.length} changing waterways (${base.rivers.length} total)`);
